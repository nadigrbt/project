// Отзывы пациентов с Яндекс Карт — блок «Отзывы» на главной (под картой).
//
// ВАЖНО: только настоящие отзывы на 5 звёзд, скопированные с карточки филиала в Яндекс Картах.
// Ничего не придумывать и не переписывать (можно сократить, поставив «…»).
// Имя автора — как оно подписано на Яндексе.
//
// Сейчас здесь ЗАГЛУШКИ (placeholder: true), чтобы был виден дизайн блока.
// Как заменить: впишите author, date, text настоящего отзыва и удалите строчку placeholder: true.
// Лучше 3–5 отзывов на филиал. Порядок карточек — как в списке.
//
// branch — номер филиала в site.branches (src/data/site.ts): 0 — Карла Либкнехта, 1 — Воровского, 2 — Кольский.
// Ссылка «Все отзывы на Яндекс Картах» строится сама из ссылки на карточку филиала.

export type Review = {
  author: string;  // имя как на Яндексе, например «Анна К.»
  date: string;    // дата как на Яндексе, например «12 октября 2026»
  text: string;
  placeholder?: boolean; // true — заглушка, а не настоящий отзыв
};

export type BranchReviews = {
  branch: number;
  tab: string; // короткое название филиала на переключателе
  reviews: Review[];
};

const stub = (n: number): Review => ({
  author: `[Имя автора ${n}]`,
  date: '[дата]',
  text: '[Текст отзыва на 5 звёзд с Яндекс Карт. Здесь будет настоящий отзыв пациента этого филиала — дословно, как на Яндексе. Длинный отзыв сворачивается, и появляется кнопка «Читать полностью».]',
  placeholder: true,
});

export const reviews: BranchReviews[] = [
  { branch: 0, tab: 'Карла Либкнехта, 28', reviews: [stub(1), stub(2), stub(3), stub(4)] },
  { branch: 1, tab: 'Воровского, 5/23', reviews: [stub(1), stub(2), stub(3)] },
  { branch: 2, tab: 'Кольский, 97/3', reviews: [stub(1), stub(2), stub(3)] },
];
